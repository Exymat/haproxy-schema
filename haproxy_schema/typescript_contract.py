"""Emit metadata TypeScript declarations from the generator's Python contract.

Run from haproxy-schema: python -m haproxy_schema.typescript_contract --out PATH
Use --check in CI to reject stale declarations. No third-party dependencies.
"""
import argparse
import json
from pathlib import Path
from typing import Literal, NotRequired, get_args, get_origin, get_type_hints, is_typeddict

from . import metadata_contract


def typescript_type(annotation: object) -> str:
    primitives = {str: "string", int: "number", bool: "boolean"}
    if annotation in primitives:
        return primitives[annotation]
    origin = get_origin(annotation)
    args = get_args(annotation)
    if origin is Literal:
        return " | ".join(json.dumps(value) for value in args)
    if origin is NotRequired:
        return typescript_type(args[0])
    if origin is list:
        return f"Array<{typescript_type(args[0])}>"
    if origin is dict and args[0] is str:
        return f"Record<string, {typescript_type(args[1])}>"
    if is_typeddict(annotation):
        return annotation.__name__
    raise TypeError(f"Unsupported contract annotation: {annotation!r}")


def render() -> str:
    lines = ["/** Generated by haproxy_schema.typescript_contract. Do not edit. */"]
    for model in vars(metadata_contract).values():
        if not is_typeddict(model):
            continue
        lines.append(f"export interface {model.__name__} {{")
        for name, annotation in get_type_hints(model).items():
            optional = "?" if name in model.__optional_keys__ else ""
            lines.append(f"  {name}{optional}: {typescript_type(annotation)};")
        lines.append("}")
        lines.append("")
    kinds = ", ".join(json.dumps(value) for value in get_args(metadata_contract.ArgumentValueKind))
    lines.extend([f"export const ARGUMENT_VALUE_KINDS = [{kinds}] as const;", ""])
    lines.extend([
        "export type KeysOfType<T, V> = {",
        "  [K in keyof T]-?: NonNullable<T[K]> extends V ? K : never;",
        "}[keyof T];",
        "",
        "export type RecordKeys<T> = Exclude<KeysOfType<T, object>, KeysOfType<T, Array<unknown>>>;",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not args.out.is_file() or args.out.read_text(encoding="utf-8") != content:
            parser.exit(1, "Generated metadata types are stale; regenerate the contract.\n")
    else:
        args.out.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
